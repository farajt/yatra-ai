"""Render a finished graph state as a Markdown trip plan (CLI output, download file, UI)."""
from yatra.formatting import format_day, format_inr
from yatra.schemas import BudgetReport, TripRequest


def _travellers(req: TripRequest) -> str:
    text = f"{req.adults} adult{'s' if req.adults > 1 else ''}"
    if req.children:
        text += f", {req.children} child{'ren' if req.children > 1 else ''}"
    return text


def _budget_section(b: BudgetReport) -> list[str]:
    out = ["## Budget", "", "| Item | Amount | Notes |", "|---|---:|---|"]
    out += [f"| {line.label} | {format_inr(line.amount_inr)} | {line.note} |" for line in b.lines]
    out.append(f"| **Total** | **{format_inr(b.total_inr)}** | |")
    if b.within_budget is not None:
        verdict = (f"Within your budget of {format_inr(b.budget_inr)}, with "
                   f"{format_inr(b.difference_inr)} to spare." if b.within_budget
                   else f"**Over your budget of {format_inr(b.budget_inr)} by "
                        f"{format_inr(-b.difference_inr)}.**")
        out += ["", verdict]
    if b.assumptions:
        out += ["", "Assumptions:"] + [f"- {a}" for a in b.assumptions]
    return out


def render_report(state: dict) -> str:
    req: TripRequest | None = state.get("request")
    errors = state.get("errors") or []

    if state.get("status") == "failed" or req is None:
        lines = ["# Trip plan could not be created", ""]
        lines += [f"- {e}" for e in errors] or ["- Unknown error"]
        return "\n".join(lines) + "\n"

    lines = [
        f"# {req.destination_city} trip plan",
        "",
        f"**Route:** {req.origin_city} → {req.destination_city}  ",
        f"**Dates:** {format_day(req.start_date)} → {format_day(req.end_date)} ({req.nights} nights)  ",
        f"**Travellers:** {_travellers(req)} · **Style:** {req.style.value}",
    ]
    if req.interests or req.dietary:
        lines.append(f"**Interests:** {', '.join(req.interests) or '-'} · "
                     f"**Dietary:** {', '.join(req.dietary) or '-'}")
    for a in state.get("assumptions") or []:
        lines.append(f"> Note: {a}")

    budget: BudgetReport | None = state.get("budget")
    if budget:
        lines += [""] + _budget_section(budget)

        if budget.selected_flight:
            lines += ["", "## Flight", "", f"**Selected:** {budget.selected_flight.summary()}"]
            others = [f for f in state.get("flights") or [] if f is not budget.selected_flight
                      and f.summary() != budget.selected_flight.summary()][:3]
            if others:
                lines += ["", "Other options:"] + [f"- {f.summary()}" for f in others]

        if budget.selected_hotel:
            h = budget.selected_hotel
            lines += ["", "## Hotel", "", f"**Selected:** {h.summary()}"]
            if h.link:
                lines.append(f"[Hotel website]({h.link})")

    weather = state.get("weather") or []
    if weather:
        title = "Weather forecast" if weather[0].source == "forecast" else "Typical weather (same dates last year)"
        lines += ["", f"## {title}", "", "| Day | Conditions | Temp (°C) | Rain (mm) |", "|---|---|---|---|"]
        for w in weather:
            lines.append(f"| {format_day(w.day)} | {w.condition} | {w.temp_min_c} – {w.temp_max_c} | "
                         f"{w.precip_mm if w.precip_mm is not None else '-'} |")

    brief = state.get("brief")
    if brief:
        lines += ["", "## Destination brief", "", brief.summary]
        if brief.visa_info:
            lines += ["", f"**Visa ({req.passport_country} passport):** {brief.visa_info.strip()} "
                          "*Always verify on the official embassy / e-visa website before booking.*"]
        if brief.local_tips:
            lines += ["", "**Tips:**"] + [f"- {t}" for t in brief.local_tips]

    if state.get("itinerary"):
        lines += ["", "## Itinerary", "", state["itinerary"]]

    if brief and brief.sources:
        lines += ["", "## Sources", ""] + [f"- {u}" for u in brief.sources]

    if errors:
        lines += ["", "## Warnings", ""] + [f"- {e}" for e in errors]

    lines += ["", f"*Generated by Yatra AI · {state.get('llm_calls', 0)} LLM calls*"]
    return "\n".join(lines) + "\n"
